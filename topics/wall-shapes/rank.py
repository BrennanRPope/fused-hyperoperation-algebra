"""Shape II test: one scale versus several independent scales (DRAFT, Nov 27 2026).

Union fractals on [0,1] made of maps f(x) = lam*x + t with exact rational data.
For each scale delta we take the 'stopping words' (cylinder just below delta) and count
distinct neighbour maps g = f_u^{-1} f_v over overlapping pairs u != v.
Finitely many neighbour maps = finite type (exact statements reduce to a finite automaton).
A count that keeps growing = no finite automaton; exact statements need arithmetic per size.
Writes rank.json.
"""
import json, math
from fractions import Fraction as F

SYSTEMS = {
  # name: (maps as (lam, t)), multiplicative rank of the group generated by the ratios
  "rank 1 (ratios 1/3)":            ([(F(1,3),F(0)),(F(1,3),F(1,4)),(F(1,3),F(1,2)),(F(1,3),F(2,3))], 1),
  "rank 1 (ratios 1/3, 1/9)":       ([(F(1,3),F(0)),(F(1,9),F(2,9)),(F(1,3),F(1,3)),(F(1,3),F(2,3)),(F(1,9),F(5,9))], 1),
  "rank 2 (ratios 1/2, 1/3)":       ([(F(1,2),F(0)),(F(1,3),F(1,3)),(F(1,3),F(2,3)),(F(1,2),F(1,2))], 2),
  "rank 3 (ratios 1/2, 1/3, 1/5)":  ([(F(1,2),F(0)),(F(1,3),F(1,3)),(F(1,5),F(4,5)),(F(1,2),F(1,2))], 3),
}

def dstar(maps):
    lo, hi = 0.0, 5.0
    for _ in range(200):
        m = (lo+hi)/2
        s = sum(float(l)**m for l,_ in maps)
        lo, hi = (m, hi) if s > 1 else (lo, m)
    return lo

def stopping(maps, delta):
    out = []
    stack = [(F(1), F(0))]   # composite (lam, t) of f_w
    while stack:
        lam, t = stack.pop()
        if lam <= delta:
            out.append((lam, t)); continue
        for l, s in maps:
            stack.append((lam*l, lam*s + t))
    return out

def neighbours(words):
    words = sorted(set(words), key=lambda w: w[1])    # exact duplicates removed (exact overlaps)
    g = set()
    for i, (lu, tu) in enumerate(words):
        ru = tu + lu
        for j in range(i+1, len(words)):
            lv, tv = words[j]
            if tv > ru: break
            g.add((lv/lu, (tv-tu)/lu))   # f_u^{-1} f_v
            g.add((lu/lv, (tu-tv)/lv))
    return g

def run(levels=(3,4,5,6,7,8,9,10)):
    res = {}
    for name, (maps, rank) in SYSTEMS.items():
        rows = []
        for m in levels:
            delta = F(1, 3**m)
            w = stopping(maps, delta)
            if len(w) > 2_500_000: break
            g = neighbours(w)
            offs = sorted({float(b) for a, b in g if a == 1 and b > 0})
            rows.append({"level": m, "words": len(w), "distinct_words": len(set(w)),
                         "neighbour_maps": len(g)})
            print(name, m, len(w), len(g), flush=True)
        res[name] = {"rank": rank, "dstar": dstar(maps), "rows": rows}
    return res

if __name__ == "__main__":
    out = run()
    json.dump(out, open("rank.json", "w"), indent=1)
