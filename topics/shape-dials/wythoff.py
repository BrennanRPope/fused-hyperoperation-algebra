"""Wythoff's kaleidoscope as the shape-choice dial (DRAFT).

A finite reflection group (Coxeter group) is picked by its diagram: a chain of mirrors with angle labels.
A seed point inside the fundamental chamber is reflected in every mirror; its orbit is the polytope's corner set.
Seed at chamber corner k ("ring node k") gives the k-rectified regular polytope; seeds on the chamber edge between
corners k and k+1 give the truncations in between.  Depth t in [0, d-1] walks corner 0 -> corner 1 -> ... -> corner d-1
(regular polytope -> rectified -> ... -> dual).  Existing names: Wythoff construction (1918), Coxeter's ringed
diagrams, truncation / rectification (Conway's operators).
"""
import numpy as np

CHAINS = {  # chain diagrams: labels between consecutive nodes
    "I2(n)": None,          # filled in by family_roots
    "A3": [3, 3], "B3": [4, 3], "H3": [5, 3],
    "A4": [3, 3, 3], "B4": [4, 3, 3], "F4": [3, 4, 3], "H4": [5, 3, 3],
    "A5": [3, 3, 3, 3], "B5": [4, 3, 3, 3],
}


def chain_roots(labels):
    d = len(labels) + 1
    G = np.eye(d)
    for i, m in enumerate(labels):
        G[i, i + 1] = G[i + 1, i] = -np.cos(np.pi / m)
    L = np.linalg.cholesky(G)      # rows are unit simple roots with the right angles
    return L


def roots_for(name, n=None):
    if name == "I2(n)":
        return chain_roots([n])
    return chain_roots(CHAINS[name])


def chamber_corners(R):
    """Unit vectors nu_k with nu_k . alpha_j = 0 for j != k, nu_k . alpha_k > 0."""
    W = np.linalg.inv(R).T          # rows w_k with w_k . alpha_j = delta_kj
    return W / np.linalg.norm(W, axis=1, keepdims=True)


def orbit(R, s, cap=20000, nd=8):
    """All images of s under the reflection group generated by unit roots R (rows)."""
    def refl(x, a):
        return x - 2 * (x @ a) * a
    seen = {tuple(np.round(s, nd)): s}
    frontier = [s]
    while frontier:
        new = []
        for x in frontier:
            for a in R:
                y = refl(x, a)
                k = tuple(np.round(y, nd))
                if k not in seen:
                    seen[k] = y
                    new.append(y)
        frontier = new
        if len(seen) > cap:
            raise RuntimeError("orbit too large")
    return np.array(list(seen.values()))


def seed_at(R, t):
    """Seed for depth t in [0, d-1]: walk along the chamber's edge path corner 0 -> 1 -> ... (unit circumradius)."""
    C = chamber_corners(R)
    d = len(C)
    t = min(max(t, 0.0), d - 1.0)
    k = min(int(np.floor(t)), d - 2)
    f = t - k
    s = (1 - f) * C[k] + f * C[k + 1]
    return s / np.linalg.norm(s)


def wythoff_polytope(name, t, n=None):
    R = roots_for(name, n)
    return orbit(R, seed_at(R, t))
