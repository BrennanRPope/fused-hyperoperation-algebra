# 8. landscape countries by prime: F_{p,q}(a,b)=(a+b+k ab)/(1-q ab), count group size on P^1(F_p)
def wall_count(k,qv,p):
    # walls are roots of 1 + k a + q a^2 in P^1 (a=inf is a root iff q=0)
    r=sum(1 for a in range(p) if (1+k*a+qv*a*a)%p==0)
    if qv%p==0: r+=1
    return r
def legendre(d,p):
    d%=p
    if d==0: return 0
    return 1 if pow(d,(p-1)//2,p)==1 else -1
good=True; samples=[]
for (k,qv) in [(1,0),(0,1),(2,1),(0,-1),(1,1),(3,1)]:
    for p in [3,5,7,11,13,17,19,23,29]:
        D=(k*k-4*qv)
        size=p+1-wall_count(k,qv,p)
        exp_=p-legendre(D,p)
        good &= size==exp_
        samples.append(((k,qv),p,size))
ok('8 group size on the projective line over F_p = p - (Δ/p): two walls p-1, turning p+1, border p', good)
# tangent addition (0,1): split exactly when p ≡ 1 mod 4
