# power series with zero constant term form a group under ⊕ (radical ring): inverse series of x
def ser_ma(f,g,L):
    h=[0]*L
    for i in range(L): h[i]+=f[i]+g[i]
    for i in range(L):
        for j in range(L-i): h[i+j]+=f[i]*g[j]
    return h
L=8; x=[0,1]+[0]*(L-2)
inv=[0]+[(-1)**n for n in range(1,L)]  # -x/(1+x) = -x + x^2 - ...
inv=[0]+[-(-1)**(n-1) for n in range(1,L)]
