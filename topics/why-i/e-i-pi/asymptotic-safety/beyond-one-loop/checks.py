def proj_ok(trials=40):
    good = True
    for _ in range(trials):
        Mm = rng.normal(size=(3, 3)); mu, E = np.linalg.eig(Mm)
        if np.any(np.abs(mu.imag) > 1e-9):
            nreal = sum(1 for j in range(3) if abs(mu[j].imag) < 1e-9 and abs(E[0, j]) > 1e-9); good &= nreal <= 1; continue
        def V(p):
            X = np.array([1.0, p[0], p[1]]); Y = Mm @ X; return np.array([Y[1] - p[0]*Y[0], Y[2] - p[1]*Y[0]])
        for i in range(3):
            if abs(E[0, i]) < 1e-6: continue
            p = (E[1:, i]/E[0, i]).real; ev = np.sort(np.linalg.eigvals(jac(V, p)).real)
            good &= np.allclose(ev, np.sort([mu[j].real - mu[i].real for j in range(3) if j != i]), atol=1e-5)
    return good
