# T2 coordinate-free test
def flow_map(beta, g0, T, n=400):
    return rk4(lambda v: np.array([beta(v[0])]), [g0], T/n, n)[-1, 0]
def affine_resid(beta, gs, T=0.4):
    g0 = np.linspace(0.05, 0.85, 9)*gs; u0 = 1/g0; uT = np.array([1/flow_map(beta, x, T) for x in g0])
    A = np.vstack([u0, np.ones_like(u0)]).T; sol, *_ = np.linalg.lstsq(A, uT, rcond=None)
    return np.max(np.abs(A @ sol - uT))/np.ptp(uT)
