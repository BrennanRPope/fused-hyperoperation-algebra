"""Writes assumptions.md, graph.json and prerequisites.csv from data.py and assumptions.py.
Run: python3 -I export.py (needs networkx)."""
import os, sys, json, csv
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from data import *
from assumptions import W, CATS
import networkx as nx

KIND = {"K": "known", "O": "ours", "in": "input"}

def assumptions_md():
    L = ["# What each write-up on the path assumes", "",
         "Drawn from each write-up's own text, its checks and its Lean hypotheses. Each line is tagged "
         "**known** (rests on a published result), **ours** (rests on a step of ours) or **input** "
         "(put in by hand), and **stated** (the write-up says so) or **implicit** (it uses it without saying).",
         "", "The grid version is figures/d8-assumptions-matrix.png. Generated by export.py from assumptions.py.", ""]
    for w in W:
        L += [f"## {w['name']}  (`{w['folder']}`)", "",
              f"- **Checks:** {w['checks']}", f"- **Lean:** {w['lean']}", ""]
        L += ["| Assumption | Rests on | Said? |", "|---|---|---|"]
        for text, kind, said in w["assumptions"]:
            L.append(f"| {text.replace('|', '/')} | {KIND.get(kind, kind)} | {said} |")
        L += ["", f"- **Known:** {w['known']}", f"- **Ours:** {w['ours']}", ""]
    return "\n".join(L) + "\n"

def graph():
    G = nx.DiGraph()
    for k, v in NODES.items():
        G.add_node(k, label=v[0].replace("\n", " "), layer=v[1])
    for a, b, t, n in EDGES:
        G.add_edge(a, b, kind=EDGE_STYLE[t][0], note=n)
    for k, (lab, targets) in INPUTS.items():
        for t in targets:
            G.add_edge(k, t, kind="outside input", note=lab.replace("\n", " "))
        G.nodes[k].update(label=lab.replace("\n", " "), layer=-1)
    H = nx.DiGraph([(a, b) for a, b, t, _ in EDGES if t in "LN"])
    reach = nx.descendants(H, "MA") | {"MA"}
    out = {"nodes": [dict(id=n, **G.nodes[n]) for n in G],
           "edges": [dict(source=a, target=b, **G.edges[a, b]) for a, b in G.edges],
           "cycles": list(nx.simple_cycles(G)),
           "not_reachable_by_lean_or_checked_links": [n for n in NODES if n not in reach],
           "lean_modules": {m: dict(theorems=t, imports=i) for m, (t, i) in LEAN.items()}}
    return out

with open(os.path.join(HERE, "assumptions.md"), "w") as f:
    f.write(assumptions_md())
with open(os.path.join(HERE, "graph.json"), "w") as f:
    json.dump(graph(), f, indent=1, ensure_ascii=False)
with open(os.path.join(HERE, "prerequisites.csv"), "w", newline="") as f:
    w = csv.writer(f)
    w.writerow(["id", "group", "prerequisite", "constants", "verdict", "what our results do", "what that rests on", "literature"])
    for p in PREREQS:
        w.writerow(list(p[:4]) + [STATUS_STYLE[p[4]][0]] + list(p[5:]))
print("wrote assumptions.md, graph.json, prerequisites.csv")
