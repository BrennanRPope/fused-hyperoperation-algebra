#!/usr/bin/env python3
"""Write the assumptions ledger from the library's theorem list.

Reads lean-library/build/theorems.tsv (written by lean-library/Check.lean on every build:
module, theorem, axioms it depends on) and writes ASSUMPTIONS.md and assumptions.csv at the
repo root. Also scans every .lean file in the library for `axiom`, `sorry`, `admit` and
`opaque` declarations. Exits non-zero if any theorem uses an axiom outside Lean's three
standard ones, or if any such declaration is found.

Usage: python3 tools/assumptions.py [--check]   (--check: fail if the ledger on disk is stale)
"""
import csv, io, re, sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LIB = ROOT / "lean-library"
STANDARD = ["propext", "Classical.choice", "Quot.sound"]
SHORT = {"propext": "propext", "Classical.choice": "choice", "Quot.sound": "Quot.sound"}
DECL = re.compile(r"^\s*(?:@\[[^\]]*\]\s*)?(?:private\s+|protected\s+|noncomputable\s+)*(axiom|opaque)\s+\S")
HOLE = re.compile(r"\b(sorry|admit)\b")


def strip_comments(text):
    text = re.sub(r"/-.*?-/", lambda m: "\n" * m.group(0).count("\n"), text, flags=re.S)
    text = re.sub(r'"(?:\\.|[^"\\\n])*"', '""', text)
    return "\n".join(line.split("--", 1)[0] for line in text.splitlines())


def scan_sources():
    found = []
    for f in sorted(LIB.rglob("*.lean")):
        if "build" in f.parts or ".lake" in f.parts:
            continue
        for i, line in enumerate(strip_comments(f.read_text()).splitlines(), 1):
            if DECL.match(line) or HOLE.search(line):
                found.append(f"{f.relative_to(ROOT)}:{i}: {line.strip()[:120]}")
    return found


def build():
    rows = []
    for line in (LIB / "build" / "theorems.tsv").read_text().splitlines():
        if not line.strip():
            continue
        parts = line.split("\t")
        mod, name = parts[0], parts[1]
        axs = [a.strip() for a in (parts[2] if len(parts) > 2 else "").split(",") if a.strip()]
        rows.append((mod, name, axs))
    rows.sort()
    bad = [(m, n, [a for a in axs if a not in STANDARD]) for m, n, axs in rows if any(a not in STANDARD for a in axs)]
    combos = Counter(", ".join(SHORT[a] for a in STANDARD if a in axs) or "none" for _, _, axs in rows)
    per_axiom = {a: sum(a in axs for _, _, axs in rows) for a in STANDARD}
    total = len(rows)

    out = io.StringIO()
    w = csv.writer(out, lineterminator="\n")
    w.writerow(["module", "theorem", "propext", "Classical.choice", "Quot.sound", "other"])
    for m, n, axs in rows:
        w.writerow([m, n] + ["yes" if a in axs else "" for a in STANDARD] + [" ".join(a for a in axs if a not in STANDARD)])
    csv_text = out.getvalue()

    mods = Counter(m for m, _, _ in rows)
    none_by_mod = Counter(m for m, _, axs in rows if not axs)
    md = [
        "# What the library rests on",
        "",
        "Generated by `python3 tools/assumptions.py` from the list `lean-library/Check.lean` writes on every build. "
        "CI regenerates this file and fails if it is out of date, if any theorem depends on an axiom other than "
        "Lean's three standard ones, or if any `axiom`, `opaque`, `sorry` or `admit` appears in the library's source. "
        "The per-theorem list is in [assumptions.csv](assumptions.csv).",
        "",
        "## Summary",
        "",
        f"- **{total} theorems.** {'None' if not bad else len(bad)} use an axiom outside the standard three; "
        "no `sorry`, no `axiom` or `opaque` declarations.",
        f"- **{combos.get('none', 0)} use no axiom at all** (they hold by computation and definitions alone).",
    ]
    for a in STANDARD:
        md.append(f"- **{per_axiom[a]} use `{a}`.**")
    md += [
        "",
        "Lean's three standard axioms are the usual foundations of mathematics in Lean: `propext` (propositions that "
        "imply each other are equal), `Quot.sound` (quotients behave as expected; it also gives function "
        "extensionality) and `Classical.choice` (the axiom of choice, which also gives the law of excluded middle). "
        "A mark means the proof as written uses that axiom; often it arrives through a standard proof tactic "
        "rather than from the mathematics itself.",
        "",
        "What Lean cannot see: each theorem's own hypotheses (such as k ≠ 0 or x > −1) are written in its statement, "
        "and modeling assumptions (that a physical system is described by a given equation, that data are "
        "representative) live in each topic's write-up. Numeric checks in `topics/*/checks.py` are evidence, not proofs.",
        "",
        "## Axiom combinations",
        "",
        "| Axioms used | Theorems |",
        "|---|---|",
    ]
    for combo, n in sorted(combos.items(), key=lambda kv: (-kv[1], kv[0])):
        md.append(f"| {combo} | {n} |")
    md += ["", "## By module", "", "| Module | Theorems | Use no axiom |", "|---|---|---|"]
    for m in sorted(mods):
        md.append(f"| `{m}` | {mods[m]} | {none_by_mod.get(m, 0)} |")
    if bad:
        md += ["", "## Non-standard axioms (CI fails on these)", ""] + [f"- `{n}` ({m}): {', '.join(x)}" for m, n, x in bad]
    return "\n".join(md) + "\n", csv_text, bad


def main():
    check = "--check" in sys.argv
    md, csv_text, bad = build()
    holes = scan_sources()
    targets = {ROOT / "ASSUMPTIONS.md": md, ROOT / "assumptions.csv": csv_text}
    stale = [p.name for p, t in targets.items() if not p.exists() or p.read_text() != t]
    if not check:
        for p, t in targets.items():
            p.write_text(t)
    ok = True
    if bad:
        ok = False
        print(f"ERROR: {len(bad)} theorem(s) use non-standard axioms:")
        for m, n, x in bad:
            print(f"  {n} ({m}): {', '.join(x)}")
    if holes:
        ok = False
        print(f"ERROR: {len(holes)} axiom/opaque/sorry/admit occurrence(s) in the library source:")
        for h in holes:
            print("  " + h)
    if check and stale:
        ok = False
        print(f"ERROR: {', '.join(stale)} out of date; run python3 tools/assumptions.py and commit.")
    print(md.split("## Axiom combinations")[0].split("## Summary")[1].strip().split("\n\nLean's")[0])
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
