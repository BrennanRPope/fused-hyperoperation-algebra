import re,glob,collections,sys
tsv=[l.split('\t') for l in open('build/theorems.tsv').read().strip().split('\n')]
order=['FusedAlgebra.Base','FusedAlgebra.Rungs','FusedAlgebra.Cube']
mods=sorted(set(r[0] for r in tsv), key=lambda m:(order.index(m) if m in order else 9, m))
docs={}
for f in glob.glob('FusedAlgebra/**/*.lean', recursive=True):
    s=open(f).read()
    for m in re.finditer(r"/--((?:(?!-/).)*?)-/\s*\n(?:@\[[^\]]*\]\s*)?theorem\s+([^\s(:{]+)", s, flags=re.S):
        docs[(f,m.group(2))]=' '.join(m.group(1).split())
out=['# Every theorem in the library','','Generated by `python3 tools/theorems_md.py` from `build/theorems.tsv`, which `Check.lean` writes. Every theorem below compiles with core Lean 4.37.0-rc1 and uses only Lean\'s standard axioms (propext, Classical.choice, Quot.sound), with no `sorry`.','']
for mod in mods:
    f=mod.replace('.','/')+'.lean'
    names=[r[1] for r in tsv if r[0]==mod]
    out.append(f'## {mod} ({len(names)})'); out.append('')
    for n in names:
        short=n.split('.')[-1]
        d=docs.get((f,short))
        out.append(f'- `{n}`' + (f': {d}' if d else ''))
    out.append('')
open('THEOREMS.md','w').write('\n'.join(out))
print(len(tsv),'theorems,',sum(1 for r in tsv if docs.get((r[0].replace('.','/')+'.lean', r[1].split('.')[-1]))),'with a docstring')
